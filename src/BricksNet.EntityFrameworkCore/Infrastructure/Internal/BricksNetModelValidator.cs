using BricksNet.EntityFrameworkCore.Metadata.Conventions;
using BricksNet.EntityFrameworkCore.Storage.Internal.Mapping;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.Extensions.Logging;

namespace BricksNet.EntityFrameworkCore.Infrastructure.Internal;

/// <summary>
/// Rejects model configuration Databricks cannot honour, at model-build time and with guidance,
/// rather than letting it fail later at runtime.
/// </summary>
/// <remarks>
/// Databricks cannot return values generated by the database (there is no <c>RETURNING</c> or
/// <c>OUTPUT</c>), so store-generated keys, defaults, computed columns and row versions are
/// rejected. Sequences do not exist. Unique indexes are not enforced and only produce a warning.
/// This is an internal API that supports the EF Core infrastructure and is not subject to the
/// same compatibility standards as public APIs.
/// </remarks>
public class BricksNetModelValidator : RelationalModelValidator
{
    private static readonly Action<ILogger, string, string, Exception?> UniqueIndexNotEnforced =
        LoggerMessage.Define<string, string>(
            LogLevel.Warning,
            new EventId(300_000, "BricksNet.UniqueIndexNotEnforced"),
            "The unique index on {EntityType} ({Properties}) is not enforced by Databricks; duplicate values can be inserted.");

    /// <summary>Initialises a new instance.</summary>
    public BricksNetModelValidator(
        ModelValidatorDependencies dependencies,
        RelationalModelValidatorDependencies relationalDependencies)
        : base(dependencies, relationalDependencies)
    {
    }

    /// <inheritdoc />
    public override void Validate(IModel model, IDiagnosticsLogger<DbLoggerCategory.Model.Validation> logger)
    {
        ArgumentNullException.ThrowIfNull(model);
        ArgumentNullException.ThrowIfNull(logger);

        // Before base validation, which would report an over-precise decimal as an unmappable property.
        ValidateDecimalPrecision(model);

        base.Validate(model, logger);

        ValidateNoSequences(model);
        foreach (var entityType in model.GetEntityTypes())
        {
            ValidateValueGeneration(entityType);
            ValidateCatalog(entityType);
            WarnOnUniqueIndexes(entityType, logger);
        }
    }

    private static void ValidateDecimalPrecision(IModel model)
    {
        foreach (var property in model.GetEntityTypes().SelectMany(e => e.GetDeclaredProperties()))
        {
            if (property.GetPrecision() > BricksNetDecimalTypeMapping.MaxPrecision)
            {
                throw new InvalidOperationException(
                    $"The property '{Describe(property)}' has precision {property.GetPrecision()}, but Databricks DECIMAL "
                    + $"supports at most {BricksNetDecimalTypeMapping.MaxPrecision} digits.");
            }
        }
    }

    private static void ValidateNoSequences(IModel model)
    {
        if (model.GetSequences().FirstOrDefault() is { } sequence)
        {
            throw new InvalidOperationException(
                $"The model defines the sequence '{sequence.Name}', but Databricks has no sequences. "
                + "Generate key values in .NET (for example Guid keys) instead.");
        }
    }

    private static void ValidateValueGeneration(IEntityType entityType)
    {
        foreach (var property in entityType.GetDeclaredProperties())
        {
            string? problem = null;

            if (property.GetComputedColumnSql() is not null)
            {
                problem = "is a computed column (HasComputedColumnSql)";
            }
            else if (property.GetDefaultValueSql() is not null)
            {
                problem = "has a database default (HasDefaultValueSql)";
            }
            else if (property.TryGetDefaultValue(out _))
            {
                problem = "has a database default (HasDefaultValue)";
            }
            else if (property.ValueGenerated.HasFlag(ValueGenerated.OnUpdate))
            {
                problem = property.IsConcurrencyToken
                    ? "is a database-generated row version (IsRowVersion)"
                    : "is generated by the database on update";
            }
            else if (property.ValueGenerated == ValueGenerated.OnAdd
                && property.GetValueGeneratorFactory() is null
                && !BricksNetValueGenerationConvention.IsClientGenerated(property.ClrType))
            {
                problem = "is configured to be generated by the database on insert (ValueGeneratedOnAdd)";
            }

            else if (property.IsShadowProperty()
                && property.IsPrimaryKey()
                && !property.IsForeignKey()
                && property.GetValueGeneratorFactory() is null
                && !BricksNetValueGenerationConvention.IsClientGenerated(property.ClrType))
            {
                // E.g. the key EF adds to an OwnsMany collection, which would be an identity column elsewhere.
                problem = "is a hidden key that the database would have to generate (for example the key of an "
                    + "OwnsMany collection); give the type a key property you set, or a Guid key";
            }

            if (problem is not null)
            {
                throw new InvalidOperationException(
                    $"The property '{Describe(property)}' {problem}. Databricks cannot return values generated by the "
                    + "database, so set the value in .NET instead: assign keys yourself, use a Guid key, configure a "
                    + "value generator with HasValueGenerator, or initialise the property in the entity. For an "
                    + "optimistic concurrency token, use a property you update yourself with IsConcurrencyToken.");
            }
        }
    }

    private static void ValidateCatalog(IEntityType entityType)
    {
        if (entityType.GetCatalog() is not null
            && (entityType.GetTableName() ?? entityType.GetViewName()) is not null
            && (entityType.GetSchema() ?? entityType.GetViewSchema()) is null)
        {
            throw new InvalidOperationException(
                $"The entity type '{entityType.DisplayName()}' is in Unity Catalog catalog '{entityType.GetCatalog()}' but "
                + "has no schema. Catalog-qualified names need a schema: use ToTable(name, schema) or HasDefaultSchema.");
        }
    }

    private static void WarnOnUniqueIndexes(IEntityType entityType, IDiagnosticsLogger<DbLoggerCategory.Model.Validation> logger)
    {
        foreach (var index in entityType.GetDeclaredIndexes().Where(i => i.IsUnique))
        {
            UniqueIndexNotEnforced(
                logger.Logger,
                entityType.DisplayName(),
                string.Join(", ", index.Properties.Select(p => p.Name)),
                null);
        }
    }

    private static string Describe(IReadOnlyProperty property) => $"{property.DeclaringType.DisplayName()}.{property.Name}";
}
